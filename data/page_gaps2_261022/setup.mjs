import fs from 'node:fs';
import assert from 'node:assert/strict';
const dir='data/page_gaps2_261022/',old='data/page_gaps_261022/';
const read=p=>JSON.parse(fs.readFileSync(p));
const prior=new Set(read(old+'targets.json').map(b=>b.id));
const books=read('data/top200_261022/compiled.json').currentBooks;
const before=fs.readFileSync('RECOMMENDED_BOOKS.md','utf8');
const rows=before.split(/\r?\n/).filter(l=>l.startsWith('| 20')).map((l,i)=>{const c=l.split('|').slice(1,-1).map(s=>s.trim());const title=c[3].match(/^\[(.*)\]\(/)?.[1];const b=books.find(b=>b.title===title&&b.author===c[2]);assert(b,title);return {rank:i+1,title,author:c[2],pages:c[6],id:b.id};});
const targets=rows.filter(b=>b.pages==='Unknown'&&!prior.has(b.id)).slice(0,250);
assert.equal(targets.length,250);
fs.writeFileSync(dir+'targets.json',JSON.stringify(targets,null,2)+'\n');
fs.writeFileSync(dir+'before-ledger.txt',before);
fs.writeFileSync(dir+'before-editions.json',fs.readFileSync('site/editions.json'));
fs.writeFileSync(dir+'manual.json','[]\n');
fs.writeFileSync(dir+'collect.mjs',fs.readFileSync(old+'collect.mjs','utf8').replaceAll(old,dir));
let review=fs.readFileSync(old+'review.mjs','utf8').replaceAll(old,dir);
review=review.replace(/const unresolved=\{[\s\S]*?output\[id\]\.reason=reason;\n/,'');
review=review.replace('pages<=0','pages<20');
fs.writeFileSync(dir+'review.mjs',review);
let apply=fs.readFileSync(old+'apply.mjs','utf8').replaceAll(old,dir);
apply=apply.replace(/const before=execFileSync\([^\n]+/,"const before=fs.readFileSync(dir+'before-ledger.txt','utf8');");
apply=apply.replace("ranked.filter(b=>b.c[6]==='Unknown').slice(0,250)","ranked.filter(b=>b.c[6]==='Unknown'&&b.rank>1745).slice(0,250)");
apply=apply.replace(/const oldEditions=JSON.parse\(execFileSync\([^\n]+/,"const oldEditions=read(dir+'before-editions.json');");
apply=apply.replaceAll('First 250','Next 250');
fs.writeFileSync(dir+'apply.mjs',apply);
console.log(JSON.stringify({targets:targets.length,ranks:[targets[0].rank,targets.at(-1).rank]}));
